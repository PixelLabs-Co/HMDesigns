#!/usr/bin/env python3
"""Refresh the Shop section of index.html from the Gumroad profile page.

Run by .github/workflows/update-store.yml on a schedule. Standard library only.
Rewrites everything between the shop:start / shop:end markers in index.html and
keeps store/ images in sync with the products listed. Per-product wording can be
pinned in store/overrides.json, keyed by the product permalink:
    { "izbzci": { "cat": "Wallpaper Pack · 7 wallpapers", "desc": "One line." } }
"""
import hashlib, html, json, os, re, sys, time, urllib.request
from urllib.parse import urlparse

STORE_URL = 'https://appleversedesigns.gumroad.com/'
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
INDEX = os.path.join(ROOT, 'index.html')
STORE_DIR = os.path.join(ROOT, 'store')
START, END = '<!-- shop:start (generated by scripts/update_store.py - do not edit by hand) -->', '<!-- shop:end -->'
TYPE_LABELS = {'digital': 'Digital Download', 'course': 'Course', 'ebook': 'E-book', 'membership': 'Membership',
               'bundle': 'Bundle', 'physical': 'Physical Product', 'call': 'Call', 'commission': 'Commission'}
EXT = {'image/png': 'png', 'image/jpeg': 'jpg', 'image/webp': 'webp', 'image/gif': 'gif'}


def get(url, binary=False, tries=3):
    last = None
    for i in range(tries):
        try:
            req = urllib.request.Request(url, headers={'User-Agent': 'Mozilla/5.0 (compatible; hm-designs-store-sync)'})
            with urllib.request.urlopen(req, timeout=30) as r:
                data = r.read()
                return (data, r.headers.get('Content-Type', '')) if binary else data.decode('utf-8', 'replace')
        except Exception as e:  # network hiccup: retry, then give up loudly
            last = e
            time.sleep(2 * (i + 1))
    sys.exit(f'Could not fetch {url}: {last}')


def safe_gumroad(url):
    u = urlparse(url)
    if u.scheme != 'https' or not (u.hostname == 'gumroad.com' or (u.hostname or '').endswith('.gumroad.com')):
        sys.exit(f'Refusing unexpected URL from Gumroad: {url}')
    return url


def page_props(url):
    m = re.search(r'data-page="([^"]+)"', get(url))
    if not m:
        sys.exit('Gumroad page layout changed: no data-page payload found.')
    return json.loads(html.unescape(m.group(1)))['props']


def list_products():
    props = page_props(STORE_URL)
    products, total = {}, 0
    for sec in props.get('sections', []):
        if sec.get('type') != 'SellerProfileProductsSection':
            continue
        sr = sec.get('search_results') or {}
        total = max(total, sr.get('total', 0))
        for p in sr.get('products', []):
            products.setdefault(p['permalink'], p)
    page = 2
    while len(products) < total and page <= 20:  # more products than fit on one profile page
        before = len(products)
        for sec in page_props(f'{STORE_URL}?page={page}').get('sections', []):
            if sec.get('type') == 'SellerProfileProductsSection':
                for p in (sec.get('search_results') or {}).get('products', []):
                    products.setdefault(p['permalink'], p)
        if len(products) == before:
            print(f'Warning: Gumroad lists {total} products but only {len(products)} could be read.')
            break
        page += 1
    return list(products.values())


def price_text(p):
    cents, cur = p.get('price_cents') or 0, (p.get('currency_code') or 'usd').lower()
    if cents == 0 and not p.get('is_pay_what_you_want'):
        return 'Free'
    amount = f'{cents / 100:.2f}' if cents % 100 else str(cents // 100)
    sym = {'usd': '$', 'gbp': '£', 'eur': '€'}.get(cur)
    text = f'{sym}{amount}' if sym else f'{amount} {cur.upper()}'
    if p.get('is_pay_what_you_want'):
        text += '+'
    if p.get('recurrence'):
        text += '/' + {'monthly': 'mo', 'yearly': 'yr', 'quarterly': 'qtr', 'biannually': '6mo'}.get(p['recurrence'], p['recurrence'])
    return text


def auto_description(p, url):
    m = re.search(r'name="description" content="([^"]*)"', get(url))
    text = html.unescape(m.group(1)).strip() if m else ''
    if text.lower().startswith(p['name'].lower()):
        text = text[len(p['name']):].lstrip(' :-')
    text = re.sub(r'\s+', ' ', text).rstrip('….')
    if len(text) > 140:
        cut = text[:140]
        dot = cut.rfind('. ')
        text = cut[:dot + 1] if dot > 60 else cut.rsplit(' ', 1)[0] + '…'
    return text


def sync_image(p, wanted):
    thumb = p.get('thumbnail_url')
    if not thumb:
        return None
    safe_gumroad(thumb)
    slug = re.sub(r'[^a-z0-9]+', '-', p['permalink'].lower()).strip('-')
    key = hashlib.sha1(thumb.encode()).hexdigest()[:8]  # new thumbnail => new filename => no stale browser cache
    existing = [f for f in os.listdir(STORE_DIR) if f.startswith(f'{slug}-{key}.')]
    if existing:
        name = existing[0]
    else:
        data, ctype = get(thumb, binary=True)
        name = f"{slug}-{key}.{EXT.get(ctype.split(';')[0].strip(), 'png')}"
        with open(os.path.join(STORE_DIR, name), 'wb') as f:
            f.write(data)
    wanted.add(name)
    return 'store/' + name


def card(p, img, overrides):
    e = html.escape
    url = safe_gumroad(p['url'].split('?')[0])
    ov = overrides.get(p['permalink'], {})
    cat = ov.get('cat') or TYPE_LABELS.get(p.get('native_type'), 'Digital Product')
    desc = ov.get('desc') if 'desc' in ov else auto_description(p, url)
    name = e(p['name'])
    media = (f'<img src="{e(img)}" alt="{name}" width="600" height="600" loading="lazy" />' if img else '')
    return f'''        <a class="product" href="{e(url)}" target="_blank" rel="noopener">
          <div class="product-media">{media}</div>
          <div class="product-info">
            <div>
              <div class="product-cat">{e(cat)}</div>
              <div class="product-title">{name}</div>{f'''
              <p class="product-desc">{e(desc)}</p>''' if desc else ''}
            </div>
            <span class="product-price">{e(price_text(p))}</span>
          </div>
        </a>'''


def main():
    os.makedirs(STORE_DIR, exist_ok=True)
    ov_path = os.path.join(STORE_DIR, 'overrides.json')
    overrides = json.load(open(ov_path)) if os.path.exists(ov_path) else {}
    products = list_products()
    if not products:
        print('No products found on the Gumroad profile; leaving the Shop section as it is.')
        return
    wanted = {'overrides.json'}
    cards = '\n'.join(card(p, sync_image(p, wanted), overrides) for p in products)
    block = f'''{START}
      <div class="shop-grid">
{cards}
      </div>
      <div class="links shop-links"><a href="{STORE_URL}" target="_blank" rel="noopener">Visit the full store &nearr;</a></div>
      {END}'''
    src = open(INDEX, encoding='utf-8').read()
    pat = re.compile(re.escape(START) + r'.*?' + re.escape(END), re.S)
    if not pat.search(src):
        sys.exit('Shop markers not found in index.html.')
    new = pat.sub(lambda m: block, src)
    for f in os.listdir(STORE_DIR):  # drop images of products that are gone
        if f not in wanted:
            os.remove(os.path.join(STORE_DIR, f))
    if new != src:
        open(INDEX, 'w', encoding='utf-8').write(new)
        print(f'Shop updated: {len(products)} products.')
    else:
        print(f'Shop already up to date ({len(products)} products).')


if __name__ == '__main__':
    main()
